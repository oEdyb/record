import { describe, expect, it, vi } from "vitest";
import { QuitCaptureLifecycle } from "../recording/quitCaptureLifecycle";
import { EditorCloseLifecycle } from "./editorCloseLifecycle";
import { RendererRecoveryLifecycle } from "./rendererRecoveryLifecycle";
import { ReviewHandoffLifecycle } from "./reviewHandoffLifecycle";
import { WorkspaceLifecycle } from "./workspaceLifecycle";

describe("window lifecycle ownership", () => {
	it("rejects readiness, transition and prewarm acknowledgements from superseded windows", () => {
		const log = vi.spyOn(console, "warn").mockImplementation(() => undefined);
		const windows = new WorkspaceLifecycle<object>();
		const old = {};
		const current = {};
		windows.transition({ type: "editor", window: old });
		windows.transition({ type: "editor", window: current });
		expect(windows.transition({ type: "ready", window: old })).toBe(false);
		expect(windows.isReady(current)).toBe(false);
		windows.transition({ type: "ready", window: current });
		windows.transition({ type: "switch", target: "editor", window: current });
		expect(windows.transition({ type: "settled", window: old })).toBe(false);
		windows.transition({ type: "closed", window: old });
		expect(windows.editorWindow).toBe(current);
		expect(windows.pendingSwitch?.window).toBe(current);
		expect(windows.transition({ type: "prewarm-fired", token: Symbol() })).toBe(false);
		expect(log).toHaveBeenCalledTimes(3);
		log.mockRestore();
	});
	it("keeps studio-frame ownership through compact and full layout changes", () => {
		const windows = new WorkspaceLifecycle<object>();
		const window = {};
		windows.transition({ type: "studio-frame", window, studio: true });
		windows.transition({ type: "compact", window, compact: true });
		expect(windows.isCompact(window)).toBe(true);
		expect(windows.isStudioFrame(window)).toBe(true);
		windows.transition({ type: "compact", window, compact: false });
		expect(windows.isStudioFrame(window)).toBe(true);
		windows.transition({ type: "closed", window });
		expect(windows.isStudioFrame(window)).toBe(false);
	});
	it("rejects stale review replies without revealing the replacement take", () => {
		const log = vi.spyOn(console, "warn").mockImplementation(() => undefined);
		const handoff = new ReviewHandoffLifecycle<object>();
		const ready = vi.fn();
		handoff.transition({ type: "begin", ready });
		const old = handoff.pending!.token;
		handoff.transition({ type: "bind", window: {} });
		handoff.transition({ type: "cancel" });
		handoff.transition({ type: "begin", ready });
		handoff.transition({ type: "bind", window: {} });
		expect(handoff.transition({ type: "reveal", token: old })).toBe(false);
		expect(handoff.transition({ type: "begin", ready })).toBe(false);
		expect(handoff.pending?.token).toBe(old + 1);
		expect(ready).not.toHaveBeenCalled();
		expect(log).toHaveBeenCalledTimes(2);
		log.mockRestore();
	});
	it("a close or save reply cannot bypass confirmation or force a different window", () => {
		const log = vi.spyOn(console, "warn").mockImplementation(() => undefined);
		const closes = new EditorCloseLifecycle<object>();
		const a = {};
		const b = {};
		closes.transition({ type: "dirty", window: a, dirty: true });
		expect(closes.transition({ type: "save-finished", window: a, shouldClose: true })).toBe(false);
		closes.transition({ type: "confirm", window: a });
		expect(closes.transition({ type: "choice", window: b, choice: "discard" })).toBe(false);
		closes.transition({ type: "choice", window: a, choice: "save" });
		expect(closes.state(a).kind).toBe("saving");
		closes.transition({ type: "force", window: b });
		expect(closes.state(a).kind).toBe("saving");
		closes.transition({ type: "save-finished", window: a, shouldClose: false });
		expect(closes.state(a).kind).toBe("dirty");
		expect(log).toHaveBeenCalledTimes(2);
		log.mockRestore();
	});
	it("coalesces renderer crashes and rejects a completion from an unrelated renderer", () => {
		const log = vi.spyOn(console, "warn").mockImplementation(() => undefined);
		const recovery = new RendererRecoveryLifecycle<object>();
		const a = {};
		const b = {};
		const schedule = vi.fn(async () => undefined);
		expect(recovery.transition({ type: "recover", window: a, schedule })).toBe(true);
		expect(recovery.transition({ type: "recover", window: a, schedule })).toBe(false);
		expect(recovery.transition({ type: "finished", window: b, saved: true })).toBe(false);
		expect(schedule).toHaveBeenCalledOnce();
		expect(recovery.transition({ type: "finished", window: a, saved: true })).toBe(true);
		expect(log).toHaveBeenCalledTimes(2);
		log.mockRestore();
	});
	it("rejects quit completion before Stop, and cannot reset a system shutdown", () => {
		const log = vi.spyOn(console, "warn").mockImplementation(() => undefined);
		const quit = new QuitCaptureLifecycle();
		expect(quit.transition("complete")).toBe(false);
		quit.transition("stop");
		quit.transition("system-shutdown");
		expect(quit.transition("returned")).toBe(false);
		expect(quit.state).toBe("system-shutdown");
		expect(log).toHaveBeenCalledTimes(2);
		log.mockRestore();
	});
});
